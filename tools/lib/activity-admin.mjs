import { scene, node, start, end, action, decision, connect } from './scene.mjs';

export function rulesAndUsers() {
    const a = scene('A06', 'Aktivitas memelihara aturan pemeriksaan', 1140, 990);
    a.description = 'Admin memilih status aktif, mengubah isi aturan, atau menghapus aturan. Riwayat konsultasi lama tetap tersimpan.';
    const centers = [200, 570, 940];
    ['Status penggunaan', 'Isi aturan', 'Penghapusan aturan'].forEach((name, i) => node(a, `lane${i}`, 'lane', 20 + i * 370, 20, 360, 950, name));
    start(a, 'st', 559, 50);
    action(a, 'open', 395, 100, 350, 'Buka daftar dan pilih aturan');
    decision(a, 'choose', 475, 210, 190, 'Perubahan yang diinginkan?');
    connect(a, 'e1', 'st', 'open'); connect(a, 'e2', 'open', 'choose');
    action(a, 'status', 85, 380, 230, 'Pilih aktif atau nonaktif');
    action(a, 'save-status', 85, 520, 230, 'Sistem menyimpan status baru', { tone: 'green' });
    action(a, 'list-status', 85, 660, 230, 'Tampilkan status terbaru pada daftar');
    end(a, 'end-status', 187, 820);
    connect(a, 'choose-status', 'choose', 'status', 'Status', { sides: ['left', 'top'], points: [{ x: 200, y: 254 }], labelX: 200, labelY: 340 });
    connect(a, 'e3', 'status', 'save-status'); connect(a, 'e4', 'save-status', 'list-status'); connect(a, 'e5', 'list-status', 'end-status');
    action(a, 'edit', 455, 380, 230, 'Pilih tindakan sunting');
    action(a, 'fill', 455, 500, 230, 'Ganti gangguan, urutan gejala, atau penjelasan');
    action(a, 'save-edit', 455, 640, 230, 'Sistem memeriksa lalu menyimpan perubahan', { tone: 'green' });
    end(a, 'end-edit', 557, 820);
    connect(a, 'choose-edit', 'choose', 'edit', 'Isi aturan', { sides: ['left', 'top'], points: [{ x: 570, y: 288 }], labelX: 570, labelY: 340 });
    connect(a, 'e6', 'edit', 'fill'); connect(a, 'e7', 'fill', 'save-edit'); connect(a, 'e8', 'save-edit', 'end-edit');
    action(a, 'delete', 825, 380, 230, 'Baca konfirmasi, lalu setujui penghapusan');
    decision(a, 'used', 845, 500, 190, 'Yakin ingin menghapus aturan?');
    action(a, 'keep', 775, 680, 155, 'Batal: aturan dipertahankan', { tone: 'green' }).h = 85;
    action(a, 'remove', 950, 680, 155, 'Ya: hapus aturan', { tone: 'green' }).h = 85;
    action(a, 'history', 830, 830, 220, 'Kembali ke daftar aturan');
    end(a, 'end-delete', 927, 925);
    connect(a, 'choose-delete', 'choose', 'delete', 'Hapus', { sides: ['right', 'top'], points: [{ x: 940, y: 254 }], labelX: 940, labelY: 340 });
    connect(a, 'e9', 'delete', 'used');
    connect(a, 'e10', 'used', 'keep', 'Tidak', { sides: ['left', 'top'], labelX: 800, labelY: 629 });
    connect(a, 'e11', 'used', 'remove', 'Ya', { sides: ['right', 'top'], labelX: 1063, labelY: 629 });
    connect(a, 'e12', 'keep', 'history'); connect(a, 'e13', 'remove', 'history');
    connect(a, 'e14', 'history', 'end-delete');

    const b = scene('A07', 'Aktivitas mengelola akun pelanggan', 760, 990);
    b.description = 'Admin mengubah data pelanggan atau mengaktifkan dan menonaktifkan akun. Admin tidak dapat menghapus atau menonaktifkan akunnya sendiri.';
    node(b, 'lane-u', 'lane', 20, 20, 340, 950, 'Admin');
    node(b, 'lane-s', 'lane', 380, 20, 340, 950, 'Sistem');
    start(b, 'st', 169, 50);
    action(b, 'pick', 70, 100, 220, 'Buka daftar dan pilih pelanggan');
    action(b, 'show', 430, 100, 250, 'Tampilkan nama, email, nomor telepon, dan status', { tone: 'green' });
    decision(b, 'choose', 450, 220, 210, 'Bagian yang ingin diubah?');
    action(b, 'edit', 70, 410, 220, 'Ubah nama, email, atau nomor telepon');
    action(b, 'status', 430, 410, 250, 'Pilih aktif atau nonaktif, lalu konfirmasi');
    action(b, 'check', 430, 550, 250, 'Periksa isian serta nama pengguna dan email yang sudah digunakan', { tone: 'green' });
    decision(b, 'valid', 450, 660, 210, 'Perubahan dapat disimpan?');
    action(b, 'fix', 70, 820, 220, 'Baca penjelasan, lalu perbaiki data pribadi');
    action(b, 'save', 430, 820, 250, 'Simpan perubahan dan tampilkan status terbaru', { tone: 'green' });
    end(b, 'end', 167, 915);
    connect(b, 'f1', 'st', 'pick'); connect(b, 'f2', 'pick', 'show', '', { sides: ['right', 'left'] });
    connect(b, 'f3', 'show', 'choose');
    connect(b, 'f4', 'choose', 'edit', 'Data pribadi', { sides: ['left', 'top'], labelX: 331, labelY: 357 });
    connect(b, 'f5', 'choose', 'status', 'Status akun', { labelX: 580, labelY: 366 });
    connect(b, 'f6', 'edit', 'check'); connect(b, 'f7', 'status', 'check'); connect(b, 'f8', 'check', 'valid');
    connect(b, 'f9', 'valid', 'fix', 'Belum', { sides: ['left', 'top'], labelX: 332, labelY: 767 });
    connect(b, 'f10', 'valid', 'save', 'Ya', { labelX: 580, labelY: 790 });
    connect(b, 'f11', 'fix', 'edit', '', { sides: ['left', 'left'], points: [{ x: 43, y: 849 }, { x: 43, y: 439 }] });
    connect(b, 'f12', 'save', 'end', '', { sides: ['left', 'top'] });
    return [a, b];
}
